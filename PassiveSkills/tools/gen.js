// Generate B42 resources only. The root B41 payload is deliberately not generated.
const fs = require('fs');
const path = require('path');
const D = require('./data');
const MOD = path.join(__dirname, '..', 'Contents', 'mods', 'PassiveSkills');
const MEDIA = path.join(MOD, '42', 'media');
const TR = path.join(MOD, 'common', 'media', 'lua', 'shared', 'Translate');
const CHECK = process.argv.includes('--check');
const outputs = [];
const put = (p, s) => outputs.push([p, Buffer.from(s, 'utf8')]);
const str = JSON.stringify;
const header = '-- GENERATED by tools/gen.js from tools/data.js. Do not edit by hand.\n';
const skillName = (s, lang) => lang === 'EN' ? s.en : s.pt;
let catalog = header + 'local Catalog = {}\n';
for (const k of ['TIERS', 'TIER_XP', 'TIER_WEIGHTS']) catalog += `Catalog.${k} = { ${D[k].map(str).join(', ')} }\n`;
catalog += 'Catalog.SKILLS = {\n' + D.SKILLS.map(s => `    { id = ${str(s.id)}, perk = ${str(s.perk)} },`).join('\n') + '\n}\n';
catalog += 'Catalog.LEGACY = {\n' + D.LEGACY.map(s => `    { id = ${str(s.id)}, aliasOf = ${str(s.aliasOf)} },`).join('\n') + '\n}\nreturn Catalog\n';
put(path.join(MEDIA, 'lua/shared/PassiveSkills/Catalog.lua'), catalog);
const items = [];
for (const s of D.SKILLS) D.TIERS.forEach((tier, i) => items.push({ id: s.id, skill: s, tier, i }));
for (const l of D.LEGACY) D.TIERS.forEach((tier, i) => items.push({ id: l.id, skill: D.SKILLS.find(s => s.id === l.aliasOf), tier, i }));
const itemName = it => `Magazine${it.id}_${it.tier}`;
let script = '/* GENERATED by tools/gen.js from tools/data.js. Do not edit by hand. */\nmodule Base\n{\n';
for (const it of items) script += `    item ${itemName(it)}
    {
        DisplayCategory = SkillBook,
        ItemType = base:literature,
        Weight = 0.4,
        Icon = MagazineSkillsPhoto,
        NumberOfPages = ${D.TIER_PAGES[it.i]},
        Tooltip = Tooltip_PassiveSkills_Magazine,
        StaticModel = Magazine,
        WorldStaticModel = MagazineGround,
        Tags = base:magazine,
    }

`;
put(path.join(MEDIA, 'scripts/PassiveSkills_Magazines.txt'), script.replace(/\n\n$/, '\n') + '}\n');
const options = [
  ['SpawnChance', 100, 12], ['XpPercent', 1000, 100],
  ['VHSSpawnChance', 100, 2], ['VHSXpPercent', 1000, 100],
];
const sandbox = 'VERSION = 1,\n' + options.map(([key, max, value]) => `
option PassiveSkills.${key}
{
    type = integer,
    min = 0,
    max = ${max},
    default = ${value},
    page = PassiveSkills,
    translation = PassiveSkills_${key},
}
`).join('');
put(path.join(MEDIA, 'sandbox-options.txt'), sandbox);
let vhs = header + 'return {\n';
for (const tape of D.VHS) {
  const skill = D.SKILLS.find(s => s.id === tape.skill);
  vhs += `    { id = ${str(tape.id)}, perk = ${str(skill.perk)}, code = ${str(tape.code)}, title = ${str('RM_' + tape.id + '_Title')}, lines = {\n`;
  tape.lessons.forEach((_, i) => { vhs += `        { text = ${str('RM_' + tape.id + '_L' + (i + 1))}, codes = ${str(tape.code + '+1')} },\n`; });
  vhs += '    } },\n';
}
vhs += '}\n';
put(path.join(MEDIA, 'lua/shared/PassiveSkills/VHSData.lua'), vhs);
for (const lang of ['EN', 'PTBR']) {
  const u = D.UI[lang];
  const tables = {
    ItemName: Object.fromEntries(items.map(it => ['Base.' + itemName(it), u.item(skillName(it.skill, lang), it.i + 1)])),
    IG_UI: {
      IGUI_PassiveSkills_Learned: u.learned, IGUI_PassiveSkills_AlreadyRead: u.already, IGUI_PassiveSkills_Halo: u.halo,
      ...Object.fromEntries(D.SKILLS.map(s => ['IGUI_PassiveSkills_Skill_' + s.id, skillName(s, lang)])),
    },
    Tooltip: { Tooltip_PassiveSkills_Magazine: u.tooltip },
    Sandbox: {
      Sandbox_PassiveSkills: u.page,
      Sandbox_PassiveSkills_SpawnChance: u.spawn, Sandbox_PassiveSkills_SpawnChance_tooltip: u.spawnTip,
      Sandbox_PassiveSkills_XpPercent: u.xp, Sandbox_PassiveSkills_XpPercent_tooltip: u.xpTip,
      Sandbox_PassiveSkills_VHSSpawnChance: u.vhsSpawn, Sandbox_PassiveSkills_VHSSpawnChance_tooltip: u.vhsSpawnTip,
      Sandbox_PassiveSkills_VHSXpPercent: u.vhsXp, Sandbox_PassiveSkills_VHSXpPercent_tooltip: u.vhsXpTip,
    },
    Mod: { name: u.modName, description: u.modDesc },
    Recorded_Media: {
      RM_PassiveSkillsVHS_Author: lang === 'EN' ? 'County Workshop Video' : 'Vídeo Oficina do Condado',
      RM_PassiveSkillsVHS_Subtitle: lang === 'EN' ? 'Practical Skills Series (1993)' : 'Série Habilidades Práticas (1993)',
    },
  };
  for (const t of D.VHS) {
    tables.Recorded_Media['RM_' + t.id + '_Title'] = (lang === 'EN' ? 'VHS: ' + t.en : 'VHS: ' + t.pt);
    t.lessons.forEach((line, i) => { tables.Recorded_Media['RM_' + t.id + '_L' + (i + 1)] = line[lang === 'EN' ? 0 : 1]; });
  }
  for (const [file, obj] of Object.entries(tables)) put(path.join(TR, lang, file + '.json'), JSON.stringify(obj, null, 4) + '\n');
}
let stale = 0;
for (const [p, buf] of outputs) {
  if (fs.existsSync(p) && fs.readFileSync(p).equals(buf)) continue;
  stale++;
  if (CHECK) console.log('stale: ' + path.relative(MOD, p));
  else { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, buf); }
}
if (CHECK) process.exit(stale ? 1 : 0);
console.log(`gen: ${outputs.length} files, ${stale} written`);
